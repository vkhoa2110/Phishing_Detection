def expected_text_result(url_properties, message_level, message_status, *, headline, conflict, review, reason):
    """Assemble the public response contract from explicit acceptance values."""
    url_level, url_status, complete, processed, total = url_properties
    return {
        "risk_level": headline,
        "label": LABELS[headline],
        "basis": HEADLINE_BASIS[headline],
        "scope": "message",
        "policy_version": "separate-assessments-2.0",
        "conflict": conflict,
        "requires_review": review,
        "review_reason": REVIEW[reason],
        "assessments": {
            "url": {
                "risk_level": url_level,
                "label": LABELS[url_level],
                "scope": "url",
                "status": url_status,
                "complete": complete,
                "processed": processed,
                "total": total,
                "basis": URL_BASIS,
            },
            "message": {
                "risk_level": message_level,
                "label": LABELS[message_level],
                "scope": "message",
                "status": message_status,
                "input_scope": "approved_llm_text",
                "basis": MESSAGE_BASIS,
            },
        },
    }


@pytest.mark.parametrize(
    "url_state,message_state,headline,conflict,review,reason",
    MATRIX,
    ids=[f"url-{row[0]}_message-{row[1]}" for row in MATRIX],
)
def test_all_25_text_fusion_acceptance_states(url_state, message_state, headline, conflict, review, reason):
    urls, *url_properties = deepcopy(URL_STATES[url_state])
    llm, message_level, message_status = deepcopy(MESSAGE_STATES[message_state])
    original_inputs = deepcopy((urls, llm))

    result = fuse("text", urls, llm, [])

    assert result == expected_text_result(
        url_properties, message_level, message_status,
        headline=headline, conflict=conflict, review=review, reason=reason,
    )
    assert (urls, llm) == original_inputs


@pytest.mark.parametrize(
    "message_state,headline,review",
    [("HIGH", "HIGH", False), ("WARNING", "WARNING", False),
     ("LOW", "LOW", False), ("UNKNOWN", "UNKNOWN", True),
     ("UNAVAILABLE", "UNKNOWN", True)],
)
def test_no_url_is_not_a_failed_url(message_state, headline, review):
    urls, *url_properties = deepcopy(URL_STATES["ABSENT"])
    llm, message_level, message_status = deepcopy(MESSAGE_STATES[message_state])
    assert fuse("text", urls, llm, []) == expected_text_result(
        url_properties, message_level, message_status,
        headline=headline, conflict=False, review=review, reason="none",
    )


@pytest.mark.parametrize(
    "urls,invalid_urls,url_properties,conflict,reason",
    [
        ([{"status": "ok", "risk_level": "SAFE"}], [],
         ("UNKNOWN", "unavailable", False, 0, 1), False, "incomplete_url"),
        ([{"status": "ok"}], [],
         ("UNKNOWN", "unavailable", False, 0, 1), False, "incomplete_url"),
        ([{"status": "error", "risk_level": "LOW"}], [],
         ("UNKNOWN", "unavailable", False, 0, 1), False, "incomplete_url"),
        ([], ["https://bad input"],
         ("UNKNOWN", "unavailable", False, 0, 1), False, "incomplete_url"),
        ([{"status": "ok", "risk_level": "LOW"}, {"status": "error"}], [],
         ("UNKNOWN", "partial", False, 1, 2), False, "incomplete_url"),
        ([{"status": "ok", "risk_level": "LOW"}, {"status": "ok", "risk_level": "UNKNOWN"}], [],
         ("UNKNOWN", "partial", False, 2, 2), False, "incomplete_url"),
        ([{"status": "ok", "risk_level": "HIGH"}, {"status": "error"}], ["https://bad input"],
         ("HIGH", "partial", False, 1, 3), True, "url_with_low"),
        ([{"status": "ok", "risk_level": "HIGH"}, {"status": "ok", "risk_level": "UNKNOWN"}], [],
         ("HIGH", "partial", False, 2, 2), True, "url_with_low"),
        ([{"status": "ok", "risk_level": "WARNING"}, {"status": "ok", "risk_level": "LOW"}], [],
         ("WARNING", "ok", True, 2, 2), True, "url_with_low"),
    ],
    ids=["invalid-level", "missing-level", "failed-url-with-stale-low", "invalid-input-only",
         "one-url-failed", "one-url-inconclusive", "alarm-and-two-failures",
         "alarm-and-inconclusive", "alarm-and-low"],
)
def test_invalid_or_partial_urls_cannot_be_cleared_by_a_low_message(
    urls, invalid_urls, url_properties, conflict, reason,
):
    result = fuse("text", urls, {"status": "ok", "verdict": {"risk_level": "LOW"}}, invalid_urls)
    assert result == expected_text_result(
        url_properties, "LOW", "ok", headline="LOW",
        conflict=conflict, review=True, reason=reason,
    )


@pytest.mark.parametrize(
    "llm,message_status",
    [
        ({"status": "error", "code": "OUTPUT_TRUNCATED", "verdict": {"risk_level": "LOW"}}, "error"),
        ({"status": "error", "code": "INVALID_JSON", "verdict": {"risk_level": "LOW"}}, "error"),
        ({"status": "error", "code": "TIMEOUT", "verdict": {"risk_level": "LOW"}}, "error"),
        ({"status": "disabled", "verdict": {"risk_level": "LOW"}}, "disabled"),
        ({"status": "pending", "verdict": {"risk_level": "LOW"}}, "pending"),
        ({"verdict": {"risk_level": "LOW"}}, "unavailable"),
        ({"status": "ok", "verdict": {}}, "ok"),
        ({"status": "ok", "verdict": {"risk_level": "SAFE"}}, "ok"),
    ],
    ids=["truncated", "invalid-json", "timeout", "disabled", "pending",
         "missing-status", "missing-verdict-level", "invalid-verdict-level"],
)
def test_failed_or_invalid_message_verdict_keeps_the_url_alarm(llm, message_status):
    urls, *url_properties = deepcopy(URL_STATES["HIGH"])
    assert fuse("text", urls, llm, []) == expected_text_result(
        url_properties, "UNKNOWN", message_status, headline="UNKNOWN",
        conflict=False, review=True, reason="url_with_unknown",
    )
